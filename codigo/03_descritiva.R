library(ggplot2)
d <- read.csv("dados/final/base_final.csv", fileEncoding = "UTF-8-BOM")
d$ln_taxa <- log(d$taxa_homicidio)
d$ln_dens <- log(d$densidade)
aggregate(cbind(taxa_homicidio, gini) ~ regiao, d, function(x) c(m = mean(x), dp = sd(x)))
cor(d$taxa_homicidio, d$gini)
cor(d$taxa_homicidio, d$gini, method = "spearman")
par(mfrow = c(2, 2))
hist(d$taxa_homicidio)
hist(d$ln_taxa)
hist(d$densidade)
hist(d$ln_dens)
ggplot(d, aes(gini, taxa_homicidio)) + geom_point() + geom_smooth(method = "lm") + facet_wrap(~regiao)
y <- d$taxa_homicidio - ave(d$taxa_homicidio, d$regiao)
x <- d$gini - ave(d$gini, d$regiao)
cor(x, y)